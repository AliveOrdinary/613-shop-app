"""Regenerates src/lib/pdf/assets.ts (logo PNG + Saira heading font) for the PDF builder.

Run from the repo root after changing the logo:  python3 scripts/pdf-assets.py
Needs: pip install cairosvg fonttools brotli pillow
"""
import base64, io
import cairosvg
from fontTools.ttLib import TTFont
from PIL import Image

png = cairosvg.svg2png(url="public/brand/logo-print.svg", output_width=1300)
w, h = Image.open(io.BytesIO(png)).size
f = TTFont("node_modules/@fontsource/saira/files/saira-latin-600-italic.woff2")
f.flavor = None
buf = io.BytesIO()
f.save(buf)
open("src/lib/pdf/assets.ts", "w").write(
    "// Generated by scripts/pdf-assets.py from public/brand/logo-print.svg and Saira 600 italic.\n"
    "// Embedded so the PDF builder needs no file access on the server.\n\n"
    f"export const LOGO_SIZE = {{ width: {w}, height: {h} }} as const;\n"
    f'export const LOGO_PNG_BASE64 = "{base64.b64encode(png).decode()}";\n\n'
    f'export const SAIRA_ITALIC_TTF_BASE64 = "{base64.b64encode(buf.getvalue()).decode()}";\n'
)
